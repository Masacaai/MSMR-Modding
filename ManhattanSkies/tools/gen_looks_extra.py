# gen_looks_extra.py: writes mod/src/looks_extra.inc, a SKY VARIANT entry for every atmosphere in recon/atmosphere_catalog.txt that is not already one of the
# hand-labelled looks in sky.cpp. Style is guessed from the sky texture; the label is the real file name, tidied.
import collections
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from labels_extra import LABELS

root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
src = open(root + r"\mod\src\sky.cpp", encoding="utf-8").read()
curated = {f for _, _, f in re.findall(r"\{ k(\w+), \"([^\"]+)\", \"([^\"]+)\" \}", src)}

rows = []
for line in open(root + r"\recon\atmosphere_catalog.txt", encoding="utf-8").read().splitlines()[1:]:
    t = line.split()
    if len(t) < 6 or not t[0].endswith(".atmosphere"):
        continue
    tex = " ".join(t[7:]).lower() if len(t) > 7 else ""
    rows.append((t[0], tex))


def style_of(tex):
    if not tex or "black_bg" in tex:
        return "Interior"
    if "earlymorning" in tex:
        return "Morning"
    if "overcast" in tex:
        return "Overcast"
    if "sunset" in tex:
        return "Sunset"
    if "night" in tex:
        return "Night"
    if "day" in tex or "cgskies" in tex or "skybox_hdr" in tex or "feast" in tex or "skybox_ibl" in tex:
        return "Day"
    return "Strange"


def label_of(file):
    stem = file[: -len(".atmosphere")].lower()
    for prefix in ("atm_ibl_lgt_", "atm_cine_", "atm_ibl_", "atm_lgt_cine_", "atm_lgt_", "atm_lgt", "atm_", "test_atm_"):
        if stem.startswith(prefix) and len(stem) > len(prefix) + 2:
            stem = stem[len(prefix):]
            break
    label = stem.replace("_", " ").upper()
    return label[:28].rstrip()


per_style = collections.defaultdict(list)
used = collections.defaultdict(set)
for path, tex in rows:
    file = path.split("/")[-1]
    if file in curated:
        continue
    style = style_of(tex)
    label = LABELS.get(file[: -len(".atmosphere")]) or label_of(file)
    base, n = label, 2
    while label in used[style]:
        label = (base[:25] + " " + str(n)).rstrip()
        n += 1
    used[style].add(label)
    per_style[style].append((label, file))

# a variant list in the game's row UI stays usable up to ~30 entries: overflow goes to a second style
curated_count = collections.Counter(st for st in re.findall(r"\{ k(\w+), \"[^\"]+\", \"[^\"]+\" \}", src))
for style in list(per_style):
    room = 30 - curated_count.get(style, 0)
    if len(per_style[style]) > room:
        ordered = sorted(per_style[style])
        per_style[style] = ordered[:room]
        per_style[style + "More"] = ordered[room:]

out = ["// Generated by tools/gen_looks_extra.py from recon/atmosphere_catalog.txt: the atmospheres that are not hand-labelled in sky.cpp.",
       "// { style, label (the real file name, tidied), file }. Included inside the g_looks initializer."]
for style in ("Day", "Sunset", "Morning", "Night", "NightMore", "Overcast", "Strange", "Interior"):
    for label, file in sorted(per_style[style]):
        out.append('    { k%s, "%s", "%s" },' % (style, label, file))
open(root + r"\mod\src\looks_extra.inc", "w", encoding="utf-8").write("\n".join(out) + "\n")
print({s: len(v) for s, v in per_style.items()}, "total", sum(len(v) for v in per_style.values()))
